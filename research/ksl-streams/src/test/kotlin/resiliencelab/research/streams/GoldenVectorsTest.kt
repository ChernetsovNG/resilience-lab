package resiliencelab.research.streams

import ksl.utilities.random.rng.RNStreamFactory
import org.assertj.core.api.Assertions.assertThat
import kotlin.test.Test

class GoldenVectorsTest {
    @Test
    fun `hash encoding matches independent Python vectors`() {
        assertThat(addressOf(StreamKey(42, 0, listOf("system", "api"), "processing")))
            .isEqualTo(5391452259724126168)
        assertThat(addressOf(StreamKey(0, Long.MAX_VALUE, listOf("а", "сервис"), "outcome")))
            .isEqualTo(5473535091301889625)
    }

    @Test
    fun `large native jumps match exact integer recurrence oracle`() {
        // Generated by oracle.py using integer recurrence matrices, not KSL jump constants.
        val vectors = listOf(
            Triple(0L, listOf(12345L, 12345, 12345, 12345, 12345, 12345),
                listOf("3fc041e683b58b4b", "3fd462c171103d2c", "3fd3c9b42453e25e", "3fea6d566678d634")),
            Triple(1L, listOf(870504860L, 2641697727, 884013853, 339352413, 2374306706, 3651603887),
                listOf("3fb4537e0083d661", "3fdebde1e7fa478d", "3feb77603790fe2e", "3fe6f01c6083170f")),
            Triple(2251799813685247L, listOf(1709191501L, 4222349477, 1266608840, 640307515, 126606725, 2331036540),
                listOf("3fe9d426171c5ef3", "3fc38619a8dcf4da", "3fd3f76654f90326", "3fe1f23f8f74d3a5")),
            Triple(2251799813685248L, listOf(3692455944L, 1366884236, 2968912127, 335948734, 4161675175, 475798818),
                listOf("3fe84e7e9f1fc6e2", "3fef4e51f9afa29c", "3fe5eca1ee304392", "3fd1df8d9a05a30e")),
            Triple(Long.MAX_VALUE, listOf(1131974319L, 355124822, 1562185588, 2521130989, 1605898005, 544457391),
                listOf("3fecf93d95ea820b", "3f8c15b21ed1a0ba", "3fcc7482a11eaa24", "3fe0dc41be92f56b")),
            Triple(5391452259724126168L, listOf(3276239085L, 2285437604, 3396061948, 3515611025, 3275547789, 749610587),
                listOf("3fc16d12ec289f60", "3fe24955471b954a", "3fe19b2ee20e1618", "3fe1da0d21c12aac")),
            Triple(5473535091301889625L, listOf(895275178L, 1523973560, 3563893306, 1802508416, 4046467245, 1593506205),
                listOf("3fe21f5fed197df1", "3fd077d7b7e15f46", "3fea7f2b73a7534f", "3fd439d3272efb90")),
        )
        for ((address, state, bits) in vectors) {
            val stream = streamAt(address) as RNStreamFactory.RNStream
            assertThat(stream.state().toList()).describedAs("state at %s", address).isEqualTo(state)
            assertThat(List(4) { stream.randU01().toBits().toString(16) })
                .describedAs("uniform bits at %s", address).isEqualTo(bits)
        }
    }
}
