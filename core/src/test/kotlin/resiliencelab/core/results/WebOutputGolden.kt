package resiliencelab.core.results

import kotlinx.serialization.Serializable
import kotlinx.serialization.builtins.ListSerializer
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import org.assertj.core.api.Assertions.assertThat
import resiliencelab.core.catalog.OutputCalculation
import resiliencelab.core.catalog.OutputCalculationKind
import resiliencelab.core.catalog.OutputCalculator
import resiliencelab.core.catalog.Stage1Catalog
import resiliencelab.core.document.DocumentCodec
import java.nio.file.Files
import java.nio.file.Path

/** Shared interpreter reference, regenerated by the existing UPDATE_SERIES_GOLDEN command. */
internal object WebOutputGolden {
    fun verify(root: Path) {
        val fixture = root.resolve("web/src/results/series/fixtures/catalog-outputs.json")
        val calculations =
            Stage1Catalog.catalog.types
                .flatMap { type ->
                    type.outputs.flatMap { output -> listOfNotNull(output.calculation, output.summary?.calculation) }
                }.distinct()
        val serializer = ListSerializer(CalculationGolden.serializer())
        if (System.getenv("UPDATE_SERIES_GOLDEN") == "1") {
            val cases =
                calculations.map { calculation ->
                    CalculationGolden(
                        calculation,
                        listOf(context(calculation), JsonObject(emptyMap())).map { context ->
                            CalculationCase(context, OutputCalculator.calculate(calculation, context))
                        },
                    )
                }
            Files.writeString(fixture, DocumentCodec.encode(serializer, cases))
        }
        val cases = Json.decodeFromString(serializer, Files.readString(fixture))
        assertThat(cases.map { it.calculation }).containsExactlyElementsOf(calculations)
        cases.forEach { golden ->
            golden.cases.forEach { case ->
                assertThat(OutputCalculator.calculate(golden.calculation, case.context)).isEqualTo(case.expected)
            }
        }
    }

    private fun context(calculation: OutputCalculation): JsonObject {
        fun putPath(
            objectValue: JsonObject,
            path: List<String>,
            value: JsonElement,
        ): JsonObject {
            val key = path.first()
            return JsonObject(
                objectValue +
                    (
                        key to
                            if (path.size ==
                                1
                            ) {
                                value
                            } else {
                                putPath(objectValue[key] as? JsonObject ?: JsonObject(emptyMap()), path.drop(1), value)
                            }
                    ),
            )
        }
        var result = JsonObject(emptyMap())

        fun put(
            path: String?,
            value: JsonElement,
        ) {
            if (path != null) result = putPath(result, path.split('.'), value)
        }
        put(
            calculation.field,
            when (calculation.kind) {
                OutputCalculationKind.MEAN -> Json.parseToJsonElement("""{"sumMs":15,"count":2}""")
                OutputCalculationKind.QUANTILE -> Json.parseToJsonElement("""{"p50Ms":5,"p95Ms":8,"p99Ms":9}""")
                else -> JsonPrimitive(12)
            },
        )
        put(
            calculation.divisor,
            JsonPrimitive(
                when (calculation.kind) {
                    OutputCalculationKind.RATE, OutputCalculationKind.NORMALIZED_RATIO -> 400
                    OutputCalculationKind.RATIO_TO_DIFFERENCE -> 4
                    else -> 3
                },
            ),
        )
        put(calculation.capacity, JsonPrimitive(3))
        return result
    }
}

@Serializable
private data class CalculationGolden(
    val calculation: OutputCalculation,
    val cases: List<CalculationCase>,
)

@Serializable
private data class CalculationCase(
    val context: JsonElement,
    val expected: Double? = null,
)
