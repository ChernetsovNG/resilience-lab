import type { XYPosition } from "@xyflow/react";
import { manualEdgePoints } from "./edgeGeometry";

export type EdgeControl = { kind: "segment" | "bend"; index: number };

/** Rendered turns include generated elbows and reversals, but exclude straight authored anchors. */
export function edgeBends(path: readonly XYPosition[]): { point: XYPosition; index: number }[] {
  return path.flatMap((point, index) => {
    const before = path[index - 1];
    const after = path[index + 1];
    if (before === undefined || after === undefined) return [];
    const incoming = { x: point.x - before.x, y: point.y - before.y };
    const outgoing = { x: after.x - point.x, y: after.y - point.y };
    return incoming.x * outgoing.y !== incoming.y * outgoing.x || incoming.x * outgoing.x + incoming.y * outgoing.y < 0
      ? [{ point, index }] : [];
  });
}

/** A gesture changes only local authored anchors; ports always remain measured endpoints. */
export function editEdgePoints(path: readonly XYPosition[], anchors: readonly XYPosition[], control: EdgeControl, point: XYPosition | null): XYPosition[] | null {
  // Automatic routes acquire their existing internal points on the first edit.
  // Manual routes retain their authored list, including repeated and straight anchors.
  const saved = anchors.length === 0 ? path.slice(1, -1) : anchors;
  let cursor = 0;
  const indices = saved.map((anchor, savedIndex) => {
    if (anchors.length === 0) return savedIndex + 1;
    cursor = path.findIndex((candidate, index) => index >= cursor && candidate.x === anchor.x && candidate.y === anchor.y);
    return cursor;
  });
  if (indices.some(index => index < 0)) return null;
  const at = (index: number, position: XYPosition) => Array.from(
    { length: Math.max(1, indices.filter(savedIndex => savedIndex === index).length) }, () => ({ ...position }));
  const replace = (first: number, last: number, replacement: XYPosition[]) => [
    ...saved.filter((_, index) => indices[index] < first),
    ...replacement,
    ...saved.filter((_, index) => indices[index] > last),
  ];
  const omitGenerated = (edited: XYPosition[], introduced: XYPosition[]) => {
    const rendered = manualEdgePoints(path[0], path.at(-1)!, edited);
    for (const endpoint of introduced) {
      const without = edited.filter(anchor => anchor !== endpoint);
      const routed = manualEdgePoints(path[0], path.at(-1)!, without);
      if (routed.length === rendered.length && routed.every((position, index) =>
        position.x === rendered[index].x && position.y === rendered[index].y)) edited = without;
    }
    return edited;
  };
  let edited: XYPosition[];
  if (control.kind === "bend") {
    const corner = path[control.index];
    const before = path[control.index - 1];
    const after = path[control.index + 1];
    if (corner === undefined || before === undefined || after === undefined) return null;
    if (point !== null) {
      const moved = at(control.index, point);
      edited = replace(control.index, control.index, moved);
      if (!edgeBends(manualEdgePoints(path[0], path.at(-1)!, edited)).some(bend => bend.point.x === point.x && bend.point.y === point.y)) {
        // Moving along an old segment can leave the new anchor on a straight line.
        // Keep the local incoming/outgoing directions so the requested point turns.
        const incoming = before.y === corner.y ? { x: before.x, y: point.y } : { x: point.x, y: before.y };
        const outgoing = after.y === corner.y ? { x: after.x, y: point.y } : { x: point.x, y: after.y };
        edited = omitGenerated(replace(control.index, control.index, [incoming, ...moved, outgoing]), [incoming, outgoing]);
      }
    } else if (anchors.length === 1 && anchors[0].x === corner.x && anchors[0].y === corner.y) {
      // Deleting the final authored bend restores automatic routing.
      edited = [];
    } else {
      // The default connector could recreate the deleted elbow; take its opposite corner instead.
      const replacement = before.x === after.x || before.y === after.y ? []
        : [before.y === corner.y ? { x: before.x, y: after.y } : { x: after.x, y: before.y }];
      edited = replace(control.index, control.index, replacement);
    }
  } else {
    const first = path[control.index];
    const last = path[control.index + 1];
    if (point === null || first === undefined || last === undefined) return null;
    const axis = first.y === last.y ? "y" : "x";
    const introduced: XYPosition[] = [];
    const replacement = [first, last].flatMap((endpoint, offset) => {
      const index = control.index + offset;
      const shifted = at(index, { ...endpoint, [axis]: point[axis] });
      if (!indices.includes(index)) introduced.push(shifted[0]);
      return shifted;
    });
    edited = replace(control.index, control.index + 1, replacement);
    // A shifted implicit endpoint may still be generated by the connector. Save it
    // only if removing it changes the rendered path; never prune authored anchors.
    edited = omitGenerated(edited, introduced);
  }
  return edited.length > 50 || edited.some(anchor => !Number.isFinite(anchor.x) || !Number.isFinite(anchor.y)) ? null : edited;
}
