import { selectExperiment } from "./fixtures";
import { expect, test } from "./fixtures";

test("reveals variant warnings on Model and navigates from a field hint to its variant", async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto("/");
  await selectExperiment(page, "retry-storm/retry-storm.experiment.json");
  await expect(page.getByRole("button", { name: "Run", exact: true })).toBeEnabled();
  const model = page.getByRole("tab", { name: "Model", exact: true });
  await expect(model).toHaveAttribute("aria-selected", "true");
  const client = page.getByTestId("rf__node-client");
  await page.getByRole("tab", { name: "Baseline", exact: true }).click();
  await client.click();
  const deadline = page.getByLabel("Deadline", { exact: true });
  await deadline.fill("100ms");
  await deadline.press("Enter");
  await expect(client.getByRole("img", { name: /problems: warning/ })).toBeVisible();
  await model.click();
  const edge = page.getByTestId("canvas-edge-label-gateway-to-middle");
  const clientBadge = client.getByRole("button", { name: "Warnings in variants: Baseline", exact: true });
  const edgeBadge = edge.getByRole("button", { name: "Warnings in variants: Baseline", exact: true });
  for (const badge of [clientBadge, edgeBadge]) {
    await expect(badge).toBeVisible();
    await expect(badge).toHaveClass(/diagnostic-badge--variants/);
    await expect(badge).toHaveAttribute("title", "Warnings in variants: Baseline");
    await expect(badge).toHaveCSS("border-top-style", "dashed");
  }
  const badgeSize = () => edgeBadge.evaluate(element => ({
    width: (element as HTMLElement).offsetWidth, height: (element as HTMLElement).offsetHeight,
  }));
  const originalBadgeSize = await badgeSize();
  await page.getByRole("button", { name: "View", exact: true }).click();
  await page.getByLabel("Interface text size", { exact: true }).selectOption("125");
  await page.getByRole("button", { name: "View", exact: true }).click();
  await expect(page.locator("html")).toHaveCSS("font-size", "20px");
  expect(await badgeSize()).toEqual(originalBadgeSize);
  await page.getByRole("button", { name: "View", exact: true }).click();
  await page.getByLabel("Interface text size", { exact: true }).selectOption("100");
  await page.getByRole("button", { name: "View", exact: true }).click();
  await page.screenshot({ path: testInfo.outputPath("model-variant-warnings.png") });
  await expect(page.getByRole("tabpanel")).toBeHidden();
  await edgeBadge.focus();
  await edgeBadge.press("Enter");
  const problems = page.getByRole("tabpanel");
  await expect(page.getByRole("tab", { name: "Problems", exact: true })).toHaveAttribute("aria-selected", "true");
  await expect(model).toHaveAttribute("aria-selected", "true");
  await expect(problems).not.toContainText("LINT_RETRY_OVERLOAD");
  await expect(problems).toContainText("LINT_TIMEOUT_BUDGET");
  await expect(problems).not.toContainText("LINT_DEADLINE_BUDGET");
  const inspector = page.getByRole("complementary", { name: "Inspector" });
  const hint = inspector.getByRole("link", { name: /^In variants: Baseline — / });
  const explanation = inspector.getByRole("dialog", { name: "Warnings in variants: Baseline", exact: true });
  const trigger = inspector.locator('[data-inspector-field="timeout"] .field-feedback--variants button');
  await trigger.click();
  await expect(explanation).toBeVisible();
  await expect(hint).toBeVisible();
  await hint.focus();
  await hint.press("Escape");
  await expect(trigger).toBeFocused();
  await expect(explanation).toBeHidden();
  await expect(hint).toBeHidden();
  await trigger.press("Enter");
  await hint.scrollIntoViewIfNeeded();
  await expect(explanation.getByRole("listitem")).toContainText("Replies may arrive too late; increase this timeout or reduce downstream timeouts and retries.");
  await page.screenshot({ path: testInfo.outputPath("model-field-and-problems.png") });
  await hint.click();
  await expect(page.getByRole("tab", { name: "Baseline", exact: true })).toHaveAttribute("aria-selected", "true");
  await expect(inspector.getByLabel("Timeout", { exact: true })).toBeFocused();
  await expect(inspector.locator(".field-diagnostics")).toContainText("LINT_TIMEOUT_BUDGET");
  await expect(inspector.locator('[data-inspector-field="timeout"] .field-feedback button')).toHaveCSS("color", "rgb(146, 64, 14)");
  await expect(edge.locator(".diagnostic-badge--variants")).toBeHidden();
  await expect(client.getByRole("img", { name: /problems: warning/ })).toBeVisible();
  await inspector.locator('[data-inspector-field="timeout"] .field-feedback button').press("Enter");
  await expect(inspector.getByRole("tooltip")).toContainText("LINT_TIMEOUT_BUDGET");
  await page.screenshot({ path: testInfo.outputPath("variant-field-warning.png") });
  await model.click();
  await clientBadge.click();
  const position = await client.getAttribute("style");
  await clientBadge.press("ArrowRight");
  await expect(client).toHaveAttribute("style", position!);
  await expect(problems).not.toContainText("LINT_TIMEOUT_BUDGET");
  await expect(problems).toContainText("LINT_DEADLINE_BUDGET");
  await expect(inspector.getByLabel("Deadline", { exact: true }).locator("..")).toContainText("In variants: Baseline —");
  await inspector.locator('[data-inspector-field="deadline"] .field-feedback--variants button').press("Enter");
  await inspector.getByRole("link", { name: /^In variants: Baseline — / }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath("model-client-warning.png") });
  await problems.getByRole("button", { name: "Show all problems", exact: true }).click();
  await expect(problems.locator('button[data-diagnostic-code="LINT_TIMEOUT_BUDGET"]')).toBeVisible();
  await expect(problems.locator('button[data-diagnostic-code="LINT_DEADLINE_BUDGET"]')).toBeVisible();
  await expect(page.getByRole("button", { name: "Save", exact: true })).toBeEnabled();
  await page.getByRole("button", { name: "Undo", exact: true }).click();
  await expect(problems.locator('button[data-diagnostic-code="LINT_TIMEOUT_BUDGET"]')).toBeVisible();
  await expect(problems).not.toContainText("LINT_DEADLINE_BUDGET");
  await expect(page.getByRole("button", { name: "Save", exact: true })).toBeDisabled();
  await expect(page.getByRole("button", { name: "Undo", exact: true })).toBeDisabled();
});
